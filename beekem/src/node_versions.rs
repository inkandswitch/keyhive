//! The versions of a value at a tree node, each tagged with the operations
//! that generated it.

use crate::operation::CgkaOperation;
use alloc::collections::BTreeSet;
use keyhive_crypto::digest::Digest;
use nonempty::NonEmpty;

/// The operation that generated a version. For a leaf, this would either be an
/// add for its first key or an update for a rotation. For an inner node, this
/// would always be an update.
pub type VersionOrigin = Digest<CgkaOperation>;

/// The versions of a value at a tree node, in ascending order and without
/// duplicates, each with the operations that generated it.
///
/// A node has more than one version after concurrent writes. A write removes
/// the origins in its causal past from every version and a version with no
/// origins left is removed. When several operations generate the same
/// version, each is recorded as one of its origins.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct NodeVersions<V>(NonEmpty<(V, BTreeSet<VersionOrigin>)>);

impl<V: Ord + Clone> NodeVersions<V> {
    /// Construct a `NodeVersions` with all versions in `values`, each
    /// generated by `origin`.
    pub(crate) fn new(values: NonEmpty<V>, origin: VersionOrigin) -> Self {
        Self(sorted_and_deduplicated(
            values.map(|value| (value, BTreeSet::from([origin]))),
        ))
    }

    /// Merge `values`, generated by `origin`, into the node. `observed` is the
    /// set of origins in the causal past of the operation `origin`. Origins in
    /// `observed` are dropped from every version. A version with no origins
    /// remaining is removed.
    pub(crate) fn merge(
        &mut self,
        values: NonEmpty<V>,
        origin: VersionOrigin,
        observed: &BTreeSet<VersionOrigin>,
    ) {
        let mut versions = values.map(|value| (value, BTreeSet::from([origin])));
        versions.extend(self.0.iter().filter_map(|(value, origins)| {
            let unobserved: BTreeSet<_> = origins.difference(observed).copied().collect();
            (!unobserved.is_empty()).then(|| (value.clone(), unobserved))
        }));
        self.0 = sorted_and_deduplicated(versions);
    }

    /// The origins of every version at the node.
    pub(crate) fn origins(&self) -> impl Iterator<Item = VersionOrigin> + '_ {
        self.0.iter().flat_map(|(_, origins)| origins).copied()
    }

    /// The versions, in ascending order.
    pub(crate) fn values(&self) -> NonEmpty<&V> {
        let NonEmpty { head, tail } = &self.0;
        NonEmpty {
            head: &head.0,
            tail: tail.iter().map(|(value, _)| value).collect(),
        }
    }

    /// Whether the node has more than one version.
    pub fn has_conflict(&self) -> bool {
        !self.0.tail.is_empty()
    }

    /// The node's single version. Returns `None` if this is a conflict node.
    pub(crate) fn non_conflict_version(&self) -> Option<&V> {
        (!self.has_conflict()).then_some(&self.0.head.0)
    }
}

/// `versions` in ascending order of value without duplicates, with the
/// origins of equal values merged.
fn sorted_and_deduplicated<V: Ord>(
    mut versions: NonEmpty<(V, BTreeSet<VersionOrigin>)>,
) -> NonEmpty<(V, BTreeSet<VersionOrigin>)> {
    versions.sort();
    let NonEmpty { head, tail } = versions;
    let mut kept = NonEmpty::new(head);
    for (value, origins) in tail {
        let last = kept.last_mut();
        if last.0 == value {
            last.1.extend(origins);
        } else {
            kept.push((value, origins));
        }
    }
    kept
}

#[cfg(test)]
mod tests {
    use super::*;
    use alloc::vec::Vec;
    use nonempty::nonempty;

    fn op(n: u8) -> VersionOrigin {
        Digest::from([n; 32])
    }

    /// Merge `value`, generated by `origin`, which observed `observed`.
    fn write(
        node: &mut NodeVersions<u8>,
        value: u8,
        origin: VersionOrigin,
        observed: &[VersionOrigin],
    ) {
        let observed = observed.iter().copied().collect();
        node.merge(NonEmpty::new(value), origin, &observed);
    }

    #[test]
    fn a_node_with_two_versions_has_a_conflict_and_no_single_version() {
        let origin = op(0);
        let single = NodeVersions::new(nonempty![1u8], origin);
        let two = NodeVersions::new(nonempty![1u8, 2], origin);
        assert!(!single.has_conflict());
        assert_eq!(single.non_conflict_version(), Some(&1));
        assert!(two.has_conflict());
        assert_eq!(two.non_conflict_version(), None);
    }

    #[test]
    fn a_version_generated_twice_is_removed_once_each_origin_is_observed_in_any_order() {
        let (a, b, after_a, after_b) = (op(1), op(2), op(3), op(4));

        let mut b_late = NodeVersions::new(NonEmpty::new(0), a);
        write(&mut b_late, 1, after_a, &[a]);
        write(&mut b_late, 0, b, &[]);
        write(&mut b_late, 2, after_b, &[b]);

        let mut b_early = NodeVersions::new(NonEmpty::new(0), a);
        write(&mut b_early, 0, b, &[]);
        write(&mut b_early, 1, after_a, &[a]);
        write(&mut b_early, 2, after_b, &[b]);

        assert_eq!(b_late, b_early);
        assert_eq!(
            b_late.values().into_iter().copied().collect::<Vec<_>>(),
            [1, 2]
        );
    }
}
