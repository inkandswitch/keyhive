//! The versions of a value at a tree node, each tagged with the operations
//! that generated it.

use crate::operation::CgkaOperation;
use alloc::collections::{BTreeMap, BTreeSet};
use keyhive_crypto::digest::Digest;
use nonempty::NonEmpty;

/// The operation that wrote a version into the tree. For a leaf, this would
/// either be an add for its first key or an update for a rotation. For an
/// inner node, this would always be an update.
pub type VersionOrigin = Digest<CgkaOperation>;

/// The versions present at a tree node, each with the operations that
/// generated it. Should never be empty.
///
/// A node has more than one version after concurrent writes. A write removes
/// the versions whose origins are all in its causal past. Multiple
/// operations that wrote identical versions are all recorded as origins
/// for that one version (and that version can only be removed once they
/// are all observed).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct NodeVersions<V>(BTreeMap<V, BTreeSet<VersionOrigin>>);

impl<V: Ord + Clone> NodeVersions<V> {
    /// `values`, all written by `origin`.
    pub(crate) fn written(values: NonEmpty<V>, origin: VersionOrigin) -> Self {
        Self(
            values
                .into_iter()
                .map(|value| (value, BTreeSet::from([origin])))
                .collect(),
        )
    }

    /// Merge `values`, generated by `origin`, into the node. `observed` is the
    /// set of origins in the causal past of the operation `origin`. Each
    /// version whose origins are all in `observed` is removed.
    pub(crate) fn merge(
        &mut self,
        values: NonEmpty<V>,
        origin: VersionOrigin,
        observed: &BTreeSet<VersionOrigin>,
    ) {
        self.0.retain(|_, origins| {
            origins.retain(|o| !observed.contains(o));
            !origins.is_empty()
        });
        for value in values {
            self.0.entry(value).or_default().insert(origin);
        }
    }

    /// Every operation that wrote a version still here.
    pub(crate) fn origins(&self) -> impl Iterator<Item = VersionOrigin> + '_ {
        self.0.values().flatten().copied()
    }

    /// The versions, in ascending order.
    pub(crate) fn values(&self) -> impl Iterator<Item = &V> {
        self.0.keys()
    }

    /// Whether the node has more than one version.
    pub fn has_conflict(&self) -> bool {
        self.0.len() > 1
    }

    /// The node's single version. Returns `None` if this is a conflict node.
    pub(crate) fn non_conflict_version(&self) -> Option<&V> {
        if self.has_conflict() {
            None
        } else {
            self.values().next()
        }
    }
}
